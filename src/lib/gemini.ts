/**
 * Google Gemini API Client
 *
 * Lightweight, zero-dependency, ultra-fast Gemini wrapper for Next.js.
 * Reads GEMINI_API_KEY from environment variables.
 */

export interface GeminiOptions {
  model?: string;
  systemInstruction?: string;
  temperature?: number;
  maxOutputTokens?: number;
}

export function isGeminiConfigured(): boolean {
  return Boolean(process.env.GEMINI_API_KEY && process.env.GEMINI_API_KEY.trim().length > 0);
}

/**
 * Send a prompt to Google Gemini and get the raw string response.
 */
export async function generateGeminiText(
  prompt: string,
  options: GeminiOptions = {}
): Promise<string> {
  const apiKey = process.env.GEMINI_API_KEY?.trim();

  if (!apiKey) {
    throw new Error(
      "GEMINI_API_KEY is not configured in your environment (.env). Please set your Google Gemini API key."
    );
  }

  const model = options.model || "gemini-1.5-flash";
  const url = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${apiKey}`;

  const body: Record<string, unknown> = {
    contents: [
      {
        role: "user",
        parts: [{ text: prompt }],
      },
    ],
    generationConfig: {
      temperature: options.temperature ?? 0.7,
      maxOutputTokens: options.maxOutputTokens ?? 2048,
    },
  };

  if (options.systemInstruction) {
    body.systemInstruction = {
      parts: [{ text: options.systemInstruction }],
    };
  }

  const controller = new AbortController();
  const timeoutId = setTimeout(() => controller.abort(), 12000);

  try {
    const response = await fetch(url, {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
      },
      body: JSON.stringify(body),
      signal: controller.signal,
    });

    if (!response.ok) {
      const errorText = await response.text();
      // If primary model is unavailable or rate-limited, attempt fallback to 2.0-flash
      if (model === "gemini-1.5-flash" && (response.status === 404 || response.status === 429)) {
        return generateGeminiText(prompt, { ...options, model: "gemini-2.0-flash" });
      }
      throw new Error(`Gemini API error (${response.status}): ${errorText}`);
    }

    const data = await response.json();
    const text = data?.candidates?.[0]?.content?.parts?.[0]?.text;

    if (!text) {
      throw new Error("No response generated by Gemini API.");
    }

    return text.trim();
  } finally {
    clearTimeout(timeoutId);
  }
}

/**
 * Generate structured JSON output from Gemini.
 * Automatically cleans code fence markers (` ```json `) and parses the object.
 */
export async function generateGeminiJson<T = unknown>(
  prompt: string,
  options: GeminiOptions = {}
): Promise<T> {
  const jsonPrompt = `${prompt}\n\nIMPORTANT: Return ONLY valid, raw JSON. Do not wrap in markdown quotes or backticks.`;
  const rawText = await generateGeminiText(jsonPrompt, options);

  // Clean markdown backticks if any
  const cleaned = rawText
    .replace(/^```json\s*/i, "")
    .replace(/^```\s*/i, "")
    .replace(/```$/i, "")
    .trim();

  try {
    return JSON.parse(cleaned) as T;
  } catch (err) {
    throw new Error(`Failed to parse Gemini response as JSON: ${(err as Error).message}\nRaw: ${rawText}`);
  }
}

/**
 * Helper to generate an AI study plan / routine block suggestion.
 */
export async function suggestStudySchedule(
  subject: string,
  topics: string[],
  availableHours: number
) {
  const prompt = `Create an optimized, high-yield study routine for the subject "${subject}" covering topics: ${topics.join(", ")}.
Available time: ${availableHours} hours.
Break it into focused study blocks and healthy break/normal blocks.

Return JSON in this format:
{
  "summary": "Brief encouraging tip for exam preparation",
  "blocks": [
    {
      "type": "study" | "normal",
      "title": "Block Title",
      "subject": "${subject}",
      "topic": "Topic Name",
      "durationMinutes": 45,
      "notes": "What key concepts to focus on"
    }
  ]
}`;

  return generateGeminiJson<{
    summary: string;
    blocks: Array<{
      type: "study" | "normal";
      title: string;
      subject?: string;
      topic?: string;
      durationMinutes: number;
      notes?: string;
    }>;
  }>(prompt, {
    systemInstruction: "You are an elite academic coach helping a student prepare for an upcoming competitive exam.",
    temperature: 0.4,
  });
}

